#!/usr/bin/env node
'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const {analyzeHtmlText,recommendProfile,scanRoot}=require('./migration-scanner.js');
const policy=require('./presentation-policy.js');
const recipe=require('./presentation-recipe.js');
const read=name=>fs.readFileSync(path.join(__dirname,name),'utf8');
const profiles=JSON.parse(read('profiles.json'));
const css=read('presentation-spine.css');
const js=read('presentation-spine.js');
const hostCss=read('presentation-host.css');
const policySchema=JSON.parse(read('presentation-policy.schema.json'));
const recipeSchema=JSON.parse(read('presentation-recipe.schema.json'));
assert.equal(profiles.schema,'axm.presentation-spine.profiles/v1');
assert.deepStrictEqual(Object.keys(profiles.profiles).sort(),['cockpit','dashboard','lab','studio']);
Object.keys(profiles.profiles).forEach(profile=>assert(css.includes(`data-axm-profile="${profile}"`),'missing profile '+profile));
assert(css.includes('@media(prefers-reduced-motion:reduce)'));
assert(js.includes("authority:'presentation-only'"));
assert.equal(policySchema.$id,'axm.presentation-policy/v1');
assert.equal(recipeSchema.$id,'axm.presentation-recipe/v1');
assert.equal(policy.resolve({module:{id:'studio'}}).mode,'shared');
assert.equal(policy.resolve({module:{id:'studio'},userMode:'module'}).mode,'module');
assert.equal(policy.resolve({module:{id:'studio',presentation:{moduleVisual:false}},userMode:'module'}).mode,'shared');
assert.equal(policy.resolve({module:{id:'game-hub'}}).profile,'cockpit');
assert(hostCss.includes('body[data-axm-presentation-mode="shared"]'));
assert(!hostCss.includes('body[data-axm-presentation-mode="module"]'));
assert(hostCss.includes('data-axm-surface="minimal"'));
assert(hostCss.includes('data-axm-depth="dimensional"'));
assert(hostCss.includes('data-axm-motion="ambient"'));
assert(hostCss.includes('AXM presentation host v2'));
assert(hostCss.includes('Presentation only: structure, behavior and data authority remain module-owned.'));
assert(hostCss.includes('min-height: 44px'));
const normalizedRecipe=recipe.normalize(recipe.DEFAULT);
assert.equal(recipe.validate(normalizedRecipe).ok,true);
assert.equal(recipe.fingerprint(normalizedRecipe),recipe.fingerprint(recipe.normalize(recipe.DEFAULT)),'recipe fingerprint must be deterministic');
assert.equal(recipe.validate(Object.assign({},normalizedRecipe,{script:'alert(1)'})).ok,false,'recipe must refuse script authority');
const attrs={};
const fakeBody={getAttribute:key=>Object.prototype.hasOwnProperty.call(attrs,key)?attrs[key]:null,setAttribute:(key,value)=>{attrs[key]=String(value);},removeAttribute:key=>{delete attrs[key];},dispatchEvent:()=>true};
const fakeDoc={body:fakeBody,defaultView:{CustomEvent:function(type,options){this.type=type;this.detail=options.detail;}}};
assert.equal(recipe.applyToDocument(fakeDoc,normalizedRecipe,{mode:'shared'}).applied,true);
assert.equal(attrs['data-axm-surface'],'glass');
assert.equal(recipe.clearFromDocument(fakeDoc).cleared,true);
assert.equal(attrs['data-axm-surface'],undefined,'clearing recipe restores original attributes');
assert.equal(recommendProfile('tools/studio/index.html'),'studio');
assert.equal(recommendProfile('tools/verifier/index.html'),'lab');
const sample=analyzeHtmlText('hub/index.html','<body style="color:#fff"><style>.x{color:#fff}</style></body>');
assert.equal(sample.seams.presentationSpine,false);
assert(sample.recommendations.includes('declare-profile'));
assert(sample.recommendations.includes('map-local-colors-to-tokens'));
const report=scanRoot(path.join(__dirname,'..','..'));
assert.equal(report.deterministic,true);
assert(report.totals.surfaces>20,'expected real Workshop surfaces');
assert.equal(JSON.stringify(report),JSON.stringify(scanRoot(path.join(__dirname,'..','..'))),'scan must be deterministic');
console.log(`PASS Presentation Spine · 4 profiles · ${report.totals.surfaces} deterministic surface records · read-only migration advice`);
