def _criterion(
    criterion_id: str,
    label: str,
    weight: float,
    source: str,
    description: str,
) -> dict[str, Any]:
    return {
        "id": criterion_id,
        "label": label,
        "weight": weight,
        "source": source,
        "description": description,
        "score_min": 0,
        "score_max": 100,
    }


