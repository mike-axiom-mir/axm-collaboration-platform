def build_preset(kind: str, challenge_id: str, title: str, goal: str, **kwargs: Any) -> dict[str, Any]:
    key = kind.strip().lower()
    if key not in PRESETS:
        raise ValueError(f"Unknown preset {kind!r}. Available: {sorted(PRESETS)}")
    return deepcopy(PRESETS[key](challenge_id, title, goal, **kwargs))
