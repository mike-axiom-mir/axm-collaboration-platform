#!/usr/bin/env node
'use strict';
const assert=require('assert');
const Registry=require('./upgrade-registry');
const Program=require('./program.json');
const RecipeSchema=require('../asset-creation-recipe.schema.json');
const ValidationSchema=require('../asset-validation-receipt.schema.json');
const hands=Registry.list();
assert.equal(hands.length,50);
assert.equal(new Set(hands.map((item)=>item.id)).size,50);
assert.deepEqual(new Set(hands.flatMap((item)=>item.capabilities)),new Set(Program.upgrades.flatMap((item)=>item.capabilities)));
assert(hands.every((item)=>item.implementation_status==='executable-contract'&&item.functions.length&&item.canvas_types.length&&item.editable_recipe_formats.includes('axm.asset-hand-upgrade-invocation/v1')));
function hand(id){const found=hands.find((item)=>item.id===id);assert(found,id+' descriptor missing');return found;}
assert(hand('asset.adapter.godot-runtime').functions.includes('createGodotProjectBundle'));
assert(!hand('asset.adapter.native-expansion-kit').functions.includes('createGodotProjectBundle'));
assert.deepEqual(hand('asset.colour.ocio-aces2').functions,['assessColourPipeline']);
assert.deepEqual(hand('asset.colour.ocio-aces2').output_types,['application/json']);
assert(hand('asset.validator.gltf-render-fidelity').functions.includes('assessGltfFidelity'));
assert(hand('asset.material.materialx139-matrix').functions.includes('assessMaterialMatrix'));
assert(hand('asset.raster.brush-ink').functions.includes('stroke')&&!hand('asset.raster.brush-ink').functions.includes('retouch'));
assert(hand('asset.raster.retouch-matting').functions.includes('retouch'));
assert(hand('asset.3d.retopology-lod-compression').functions.includes('assessLods'));
assert(hand('asset.3d.character-deformation').functions.includes('deform'));
assert.deepEqual(hand('asset.3d.lookdev-render-aov').functions,['assessAovs']);
assert.deepEqual(hand('asset.3d.simulation-effects').functions,['simulate']);
assert(!hand('asset.world.terrain-prefab-streaming').functions.includes('simulate'));
assert(!hand('asset.document.multipage-story').output_types.includes('application/pdf'));
assert(!hand('asset.print.packaging-production').output_types.includes('application/pdf'));
assert(!hand('asset.garment.pattern-grading').output_types.includes('application/pdf'));
assert(!hand('asset.cad.sheet-metal').output_types.includes('model/step'));
assert(hand('asset.manufacturing.3mf').required_substrates.includes('official-3mf-validator'));
assert.deepEqual(hand('asset.vector.precision-path').operations,{preview:false,validate:true,edit:true});
assert.deepEqual(hand('asset.vector.precision-path').output_types,['application/json']);
assert.equal(hand('asset.typography.production').operations.edit,false);
assert.equal(hand('asset.world.terrain-prefab-streaming').operations.preview,false);
assert.deepEqual(hand('asset.video.ingest-precision-edit').operations,{preview:false,validate:true,edit:true});
const canvas={medium:'screen',dimensions:{width:3,height:2,unit:'px'},colour:{space:'srgb',transparency:'allowed'},behaviour:['static'],intended_use:'layered-raster'};
const request={schema:Registry.REQUEST_SCHEMA,required_capabilities:['asset.raster.layers'],target_canvas:canvas,intended_use:'layered-raster',quality_requirements:{strict_validation:true},required_outputs:['image/png'],editable_recipe_formats:['axm.asset-hand-upgrade-invocation/v1'],required_constraints:['target_canvas.dimensions'],available_substrates:[]};
const diagnosis=Registry.diagnose(request);
assert.equal(diagnosis.status,'READY_CONTRACT');
assert.equal(diagnosis.selected_hand.id,'asset.raster.nondestructive-document');
const benchmarkRequest=Object.assign({},request,{required_capabilities:['asset.performance.measure'],required_outputs:['application/json'],required_constraints:[]});
function registryBenchmarkWorkload(index){return{output:{index,payload:'route'},metrics:{route_runs:1}};}
const benchmarkExecuted=Registry.invoke('asset.performance.benchmark-receipts','run',[{
  workload:{id:'registry-route',digest:'declared-registry-route-v1',description:'Exercise the benchmark through the public Asset Hands registry.'},
  environment:{runtime:'declared',platform:'declared',architecture:'declared',isolation:'registry-selftest'},
  repetitions:2,warmup_repetitions:1,budgets:{duration_ms:5000,p95_duration_ms:5000,output_bytes:10000}
},registryBenchmarkWorkload],benchmarkRequest);
assert.equal(benchmarkExecuted.status,'EXECUTED');
assert.equal(benchmarkExecuted.output.status,'PASS');
assert.equal(benchmarkExecuted.output.samples.length,2);
assert.equal(benchmarkExecuted.output.workload.observed_function_digest,benchmarkExecuted.creation_recipe.parameters.arguments[1].digest);
assert.equal(benchmarkExecuted.creation_recipe.parameters.arguments[1].kind,'local-function');
assert(!Object.prototype.hasOwnProperty.call(benchmarkExecuted.creation_recipe.parameters.arguments[1],'source'));
const executed=Registry.invoke('asset.raster.nondestructive-document','create',[{id:'canvas-bound-test',layers:[{id:'base',rgba8:Buffer.alloc(3*2*4)}]}],request);
assert.equal(executed.status,'EXECUTED');
assert.equal(executed.output.width,3);
assert.equal(executed.output.height,2);
assert.deepEqual(executed.invocation.target_canvas.dimensions,{width:3,height:2,depth:null,unit:'px'});
assert.equal(executed.invocation.fallback_used,false);
assert.equal(executed.creation_recipe.schema,'axm.asset-creation-recipe/v1');
RecipeSchema.required.forEach((key)=>assert(Object.prototype.hasOwnProperty.call(executed.creation_recipe,key),'creation recipe missing '+key));
assert.equal(executed.creation_recipe.target_canvas.dimensions.width,3);
assert(executed.artifacts.some((item)=>item.mime==='application/json'));
assert.equal(executed.validation_receipt.status,'HOLD');
ValidationSchema.required.forEach((key)=>assert(Object.prototype.hasOwnProperty.call(executed.validation_receipt,key),'validation receipt missing '+key));
assert.equal(executed.delivery_status,'OUTPUT_REQUIREMENTS_HOLD');
assert(executed.missing.includes('image/png'));
assert.equal(executed.provenance.hand_id,'asset.raster.nondestructive-document');
const rendered=Registry.invoke('asset.raster.nondestructive-document','render',[executed.output],request);
assert(rendered.artifacts.some((item)=>item.mime==='image/png'&&item.dataUrl));
assert.equal(rendered.preview.mime,'image/png');
assert.equal(rendered.delivery_status,'OUTPUT_REQUIREMENTS_SATISFIED');
const unsupported=Registry.diagnose(Object.assign({},request,{target_canvas:{medium:'metal',dimensions:{width:3,height:2,unit:'mm'},colour:{space:'grayscale',transparency:'opaque'},behaviour:['static'],intended_use:'engraving'}}));
assert.equal(unsupported.status,'UNSUPPORTED_CANVAS');
assert(unsupported.missing.includes('metal'));
const unknown=Registry.diagnose(Object.assign({},request,{required_capabilities:['asset.impossible.telepathy']}));
assert.equal(unknown.status,'MISSING_HAND');
const external=Registry.diagnose({required_capabilities:['asset.audio.synthesize'],target_canvas:{medium:'audio-device',dimensions:{width:1,height:1,unit:'m'},colour:{space:'srgb',transparency:'opaque'},behaviour:['animated'],intended_use:'audible-waveform'},required_outputs:['audio/wav'],available_substrates:[]});
assert.equal(external.status,'MISSING_SUBSTRATE');
assert(external.missing.includes('audible-review'));
const production=Registry.diagnose(Object.assign({},request,{require_production_acceptance:true}));
assert.equal(production.status,'REVIEW_REQUIRED');
const composition=Registry.plan(Object.assign({},request,{required_capabilities:['asset.raster.layers','asset.raster.stroke'],available_substrates:['openimageio','openexr','opencolorio']}));
assert.equal(composition.status,'READY_CONTRACT');
assert(composition.route_plan.some((item)=>item.hand.id==='asset.raster.nondestructive-document'&&item.covers.includes('asset.raster.layers')));
assert(composition.route_plan.some((item)=>item.hand.id==='asset.raster.brush-ink'&&item.covers.includes('asset.raster.stroke')));
assert(composition.route_plan.every((item,index)=>index===0||item.hand.rank>=composition.route_plan[index-1].hand.rank));
const impossibleComposition=Registry.plan(Object.assign({},request,{required_capabilities:['asset.raster.layers','asset.unknown.unbuilt']}));
assert.equal(impossibleComposition.status,'MISSING_HAND');
assert(impossibleComposition.missing.includes('asset.unknown.unbuilt'));
const audit=Registry.audit({available_substrates:[]});
assert.equal(audit.total,50);
assert.equal(audit.items.length,50);
assert.equal((audit.counts.MISSING_SUBSTRATE||0)+(audit.counts.REVIEW_REQUIRED||0)+(audit.counts.READY||0),50);
assert(audit.items.some((item)=>item.status==='MISSING_SUBSTRATE'&&item.missing_substrates.length));
assert(audit.items.every((item)=>item.pass_condition&&item.primary_evidence&&item.counterevidence));
assert.equal(Registry.list().length,50);
console.log('Asset Hands upgrade registry PASS (50 modular extensions; canvas-bound routing and honest gaps verified)');
