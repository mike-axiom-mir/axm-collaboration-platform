'use strict';
const assert=require('assert');
const fabric=require('./human-discipline-perspective-fabric.js');
const snap=fabric.snapshot();
assert.strictEqual(snap.firstClassCount,20);
assert.strictEqual(snap.compositeRoleCount,10);
assert.strictEqual(snap.domainOverlayCount,5);
assert.strictEqual(new Set(snap.entries.map(x=>x.id)).size,20);
assert.strictEqual(fabric.route({}).result,'NO_DISCIPLINE_EVIDENCE');
const systems=fabric.route({requestedPerspectives:['systems-engineering']});
assert(systems.active.some(x=>x.perspectiveId==='systems-engineering'));
const game=fabric.route({signals:['game loop','frame','tick','input','replay','rollback']});
assert(game.active.some(x=>x.perspectiveId==='interactive-game-systems'));
const embedded=fabric.route({signals:['interrupt','RTOS','watchdog','power budget','hardware interface','peripheral']});
assert(embedded.active.some(x=>x.perspectiveId==='embedded-firmware'));
const sre=fabric.route({signals:['SLO','retry','timeout','health check','rollback','alert']});
assert(sre.active.some(x=>x.perspectiveId==='reliability-sre'));
const ml=fabric.route({signals:['model','training','dataset','drift','inference','feedback']});
assert(ml.active.some(x=>x.perspectiveId==='machine-learning-engineering'));
const ui=fabric.route({signals:['DOM','focus','ARIA','keyboard','browser','layout']});
assert(ui.active.some(x=>x.perspectiveId==='frontend-interaction-accessibility'));
const cloud=fabric.route({roleIds:['cloud-engineer']});
for(const id of ['distributed-systems','reliability-sre','security-engineering','build-release-reproducibility'])assert(cloud.active.some(x=>x.perspectiveId===id));
assert.strictEqual(cloud.compositeRoles[0].verdict,'COMPOSITE_ROLE');
const titleOnly=fabric.route({jobTitle:'cloud engineer'});
assert.strictEqual(titleOnly.active.length,0);
const role=fabric.composeRole('full-stack-engineer');
assert.strictEqual(role.result,'COMPOSITE_ROLE_RESOLVED');
assert.strictEqual(role.createsNewFundamentalLens,false);
assert.deepStrictEqual(role.perspectives.map(x=>x.perspectiveId),['frontend-interaction-accessibility','software-architecture','database-storage','distributed-systems']);
const industrial=fabric.route({domainOverlays:['industrial-control']});
for(const id of ['safety-critical','embedded-firmware','robotics-control','network-protocol','security-engineering'])assert(industrial.active.some(x=>x.perspectiveId===id));
const rustGame=fabric.compose({languageId:'rust',intent:'safe-refactor',observation:{signals:['game loop','frame','tick','input','replay']}});
const rustEmbedded=fabric.compose({languageId:'rust',intent:'safe-refactor',observation:{signals:['interrupt','RTOS','watchdog','power budget','peripheral']}});
assert.strictEqual(rustGame.languageId,'rust');
assert.strictEqual(rustEmbedded.languageId,'rust');
assert(rustGame.disciplineLayers.some(x=>x.perspectiveId==='interactive-game-systems'));
assert(rustEmbedded.disciplineLayers.some(x=>x.perspectiveId==='embedded-firmware'));
assert.notDeepStrictEqual(rustGame.disciplineLayers.map(x=>x.perspectiveId),rustEmbedded.disciplineLayers.map(x=>x.perspectiveId));
assert.strictEqual(rustGame.multiplicativePerspectiveSpace.possibleIntersections,2040);
assert.strictEqual(rustGame.multiplicativePerspectiveSpace.allActivatedByDefault,false);
assert(rustGame.templateSelection.selected.length>0);
assert.strictEqual(rustGame.authority.workspaceMutation,false);
assert.strictEqual(rustGame.authority.toolExecution,false);
for(const x of [...rustGame.disciplineLayers,...rustEmbedded.disciplineLayers]){assert.strictEqual(x.lensOutputIsProof,false);assert.strictEqual(x.authority,'NONE')}
