const rustPolicy=admission.buildPolicy({languageId:'rust'});
assert.strictEqual(rustPolicy.result,'ADMISSION_POLICY_READY');
assert(rustPolicy.checks.some(c=>c.id==='structural-parse'&&c.required));
assert(rustPolicy.checks.some(c=>c.class==='NATIVE_VALIDATE'&&c.required&&c.verifierCandidates.includes('rustc')));
assert(rustPolicy.checks.some(c=>c.class==='NATIVE_VALIDATE'&&c.required&&c.verifierCandidates.includes('cargo check')));
assert(rustPolicy.checks.some(c=>c.class==='STATIC_ANALYSIS'&&!c.required&&c.verifierCandidates.includes('clippy')));
assert(rustPolicy.checks.some(c=>c.class==='TEST_REGRESSION'&&!c.required));
const empty=admission.evaluate({languageId:'rust',candidateDigest:'sha256:fixture'});
