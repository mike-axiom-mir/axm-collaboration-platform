const passObs=admission.makePassingFixtureObservations(rustPolicy);
const admissible=admission.evaluate({languageId:'rust',candidateDigest:'sha256:fixture',observations:passObs});
assert.strictEqual(admissible.result,'ADMISSIBLE_CANDIDATE_NOT_PROMOTED');
assert.strictEqual(admissible.truth.admittedMeansPromoted,false);
assert.strictEqual(admissible.truth.admittedMeansBugFree,false);
const withTests=admission.buildPolicy({languageId:'rust',existingTests:true});
assert(withTests.checks.some(c=>c.class==='TEST_REGRESSION'&&c.required));
const strict=admission.buildPolicy({languageId:'rust',mode:'STRICT'});
