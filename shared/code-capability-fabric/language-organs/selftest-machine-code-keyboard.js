'use strict';
const assert=require('assert');
const keyboard=require('./machine-code-keyboard-fabric.js');
const router=require('./machine-code-keyboard-router.js');
const twin=require('./code-prebuild-twin.js');
const snapshot=keyboard.snapshot();
assert.strictEqual(snapshot.bankCount,102);
assert.strictEqual(snapshot.keysPerBank,48);
assert.strictEqual(snapshot.totalStableKeyCount,4896);
assert.strictEqual(new Set(snapshot.banks.map(x=>x.keyboardSha256)).size,102);
const rust=keyboard.buildBank('rust');
assert(rust);
assert.strictEqual(rust.keys.length,48);
assert.strictEqual(rust.keys[3].keyId,'K04');
assert(rust.keys[3].nativeBindings.includes('fn'));
assert(rust.keys[4].nativeBindings.includes('struct'));
assert(rust.keys.some(k=>k.actionId==='request-admission'&&k.requiresRenderer===false));
assert(rust.nativePalette.verifierCandidates.includes('rustc'));
assert(rust.nativePalette.verifierCandidates.includes('cargo check'));
const browser=twin.preview({goal:'build a browser game',roleBindings:{'document-shell':'html','style-layout':'css','game-runtime':'javascript'}});
assert.strictEqual(browser.plan.simulation.sourceGenerationReady,true);
const jsLayout=router.layout({languageId:'javascript',prebuildPlan:browser.plan,role:'game-runtime',intent:'build',signals:['game loop','input','state','render','safe verification']});
assert.strictEqual(jsLayout.result,'MACHINE_KEYBOARD_READY');
assert.strictEqual(jsLayout.hotKeys.length,12);
assert.strictEqual(new Set(jsLayout.hotKeys.map(x=>x.stableKeyId)).size,12);
assert(jsLayout.hotKeys.some(x=>x.category==='TEMPLATE'));
assert(jsLayout.hotKeys.some(x=>x.category==='CONTROL'||x.category==='TYPE_STATE'));
assert(jsLayout.hotKeys.some(x=>x.category==='VERIFY'||x.category==='GOVERNANCE'));
const jsLayoutAgain=router.layout({languageId:'javascript',prebuildPlan:browser.plan,role:'game-runtime',intent:'build',signals:['game loop','input','state','render','safe verification']});
assert.strictEqual(jsLayout.layoutSha256,jsLayoutAgain.layoutSha256);
const mismatch=router.layout({languageId:'rust',prebuildPlan:browser.plan,role:'game-runtime'});
assert.strictEqual(mismatch.result,'ROLE_LANGUAGE_MISMATCH');
const pressHot=router.press({languageId:'javascript',keyId:'H01',layout:jsLayout,arguments:{symbol:'update'},targetRef:'role:game-runtime'});
assert(['EDIT_INTENT_READY','CONTROL_INTENT_READY'].includes(pressHot.result));
assert.strictEqual(pressHot.sourceCode,null);
assert.strictEqual(pressHot.truth.workspaceMutated,false);
assert.strictEqual(pressHot.truth.toolExecuted,false);
const stale={...jsLayout,keyboardSha256:'stale'};
const stalePress=router.press({languageId:'javascript',keyId:'H01',layout:stale});
assert.strictEqual(stalePress.result,'STALE_KEYBOARD_LAYOUT');
const stablePress=router.press({languageId:'rust',keyId:'K16',arguments:{symbol:'step',kind:'fn'},targetRef:'crate'});
assert.strictEqual(stablePress.result,'EDIT_INTENT_READY');
assert.strictEqual(stablePress.rendering.state,'RENDER_HELD_NO_ADAPTER');
const rendererBound=router.press({languageId:'rust',keyId:'K16',arguments:{symbol:'step',kind:'fn'},renderer:{id:'rust-ast-renderer',digest:'sha256:fixture'}});
assert.strictEqual(rendererBound.rendering.state,'RENDERER_BOUND_EXECUTION_HELD');
assert.strictEqual(rendererBound.truth.rendererBindingIsNotExecutionAuthority,true);
const controlPress=router.press({languageId:'rust',keyId:'K43',arguments:{candidateRef:'candidate:1'}});
assert.strictEqual(controlPress.result,'CONTROL_INTENT_READY');
assert.strictEqual(controlPress.rendering.state,'NON_SOURCE_CONTROL_INTENT');
const program=router.program({languageId:'rust',presses:[{keyId:'K16',arguments:{symbol:'step',kind:'fn'}},{keyId:'K24',arguments:{conditionRef:'running'}},{keyId:'K43',arguments:{candidateRef:'candidate:1'}}]});
assert.strictEqual(program.result,'EDIT_PROGRAM_READY');
assert.strictEqual(program.sourceCode,null);
assert.strictEqual(program.truth.workspaceMutated,false);
assert(program.invalidates.includes('symbols'));
assert(program.verificationHints.includes('rustc'));
console.log(JSON.stringify({ok:true,bankCount:snapshot.bankCount,keysPerBank:snapshot.keysPerBank,totalStableKeyCount:snapshot.totalStableKeyCount,uniqueKeyboardDigests:new Set(snapshot.banks.map(x=>x.keyboardSha256)).size,rustFirstNativeKeys:rust.keys.slice(3,8).map(k=>({keyId:k.keyId,binding:k.nativeBindings[0]})),javascriptGameHotKeys:jsLayout.hotKeys.map(x=>({hotKeyId:x.hotKeyId,stableKeyId:x.stableKeyId,actionId:x.actionId,category:x.category})),keypressResult:pressHot.result,stablePressRenderState:stablePress.rendering.state,rendererBoundState:rendererBound.rendering.state,programState:program.result,snapshotSha256:snapshot.snapshotSha256,authority:'NONE'},null,2));
